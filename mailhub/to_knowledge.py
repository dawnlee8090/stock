GENERIC = {"조립불량", "광택·외관", "치수불량", "취출·이젝터"}   # 다른 유형과 같이 나오면 뒤로


def normalize_defect(text: str) -> str:
    """'SINK 발생', '싱크마크' → '싱크'. 여러 개면 구체적인 유형·앞에 나온 것 우선. 못 찾으면 원문."""
    t = (text or "").lower()
    hits = []
    for name, words in DEFECTS.items():
        for w in words:
            w = w.lower()
            if re.fullmatch(r"[a-z ]+", w):
                m = re.search(r"(?<![a-z])" + re.escape(w) + r"(?![a-z])", t)
                i = m.start() if m else -1
            else:
                i = t.find(w)
            if i >= 0:
                hits.append((name in GENERIC, i, name))
    return min(hits)[2] if hits else (text or "").strip()


def guide_text(defect: str) -> str:
    name = normalize_defect(defect)
    g = GUIDE.get(name)
    if not g:
        return f"'{defect}' 에 대한 가이드가 없습니다. 유형: {', '.join(GUIDE)}"
    out = [f"■ {name} - 원인·대책 가이드", "", "[원인]"]
    for cat, items in g["원인"].items():
        out.append(f"  ({cat}) " + " / ".join(items))
    out += ["", "[대책 우선순위]  ① 조건 → ② 금형 → ③ 설계(E.O) → ④ 재질"]
    out += [f"  {i}. {x}" for i, x in enumerate(g["대책"], 1)]
    out += ["", "[확인 항목]"] + [f"  - {x}" for x in g["확인"]]
    return "\n".join(out)
